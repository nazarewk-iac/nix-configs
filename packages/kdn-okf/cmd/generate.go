package cmd

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"kdn-okf/internal/okf"
)

// generatedMarker identifies an index.md this tool wrote. The prefix is stable; the wording says
// the file is editable, because an index is designed to be written by a human, an agent or this
// tool. A file without the marker is human-authored and is never overwritten unless --force.
const (
	generatedMarker = "<!-- generated by kdn-okf; edit freely; a regeneration replaces this file -->"
	generatedPrefix = "<!-- generated by kdn-okf;"
)

type generateEntry struct {
	Dir    string `json:"dir"`
	Path   string `json:"path"`
	Action string `json:"action"`
	Reason string `json:"reason,omitempty"`
}

func newGenerateIndexCmd(app *App) *cobra.Command {
	var (
		dryRun bool
		force  bool
		check  bool
	)
	cmd := &cobra.Command{
		Use:   "generate-index",
		Short: "Write a deterministic index.md in every directory with concepts",
		Long: "Write one index.md per directory that holds concepts. The file is a directory listing:\n" +
			"a summary, every direct concept with its description, and every child directory with its\n" +
			"own summary. It is deterministic: no timestamps, sorted entries, and a marker that says\n" +
			"the file may be edited. An existing human-authored index.md is refused unless --force is\n" +
			"explicit. --check exits 1 when a generated index is missing or out of date, for CI.",
		RunE: func(cmd *cobra.Command, args []string) error {
			return app.generateIndex(dryRun, force, check)
		},
	}
	cmd.Flags().BoolVar(&dryRun, "dry-run", false, "print the plan and write nothing")
	cmd.Flags().BoolVar(&force, "force", false, "overwrite a human-authored index.md")
	cmd.Flags().BoolVar(&check, "check", false, "exit 1 when a generated index is missing or stale")
	return cmd
}

func (a *App) generateIndex(dryRun, force, check bool) error {
	result, err := a.load()
	if err != nil {
		return err
	}
	dirs := map[string]bool{".": true}
	for _, concept := range result.Bundle.Concepts {
		dir := path.Dir(concept.RelPath)
		for dir != "." && dir != "/" {
			dirs[dir] = true
			dir = path.Dir(dir)
		}
	}
	ordered := make([]string, 0, len(dirs))
	for dir := range dirs {
		ordered = append(ordered, dir)
	}
	sort.SliceStable(ordered, func(i, j int) bool {
		if ordered[i] == "." {
			return true
		}
		if ordered[j] == "." {
			return false
		}
		return ordered[i] < ordered[j]
	})

	entries := make([]generateEntry, 0, len(ordered))
	failed := false
	for _, dir := range ordered {
		content := renderGeneratedIndex(result.Bundle, dir)
		target := filepath.Join(a.Bundle, filepath.FromSlash(dir), "index.md")
		entry := generateEntry{Dir: dir, Path: target}
		existing, readErr := os.ReadFile(target)
		switch {
		case os.IsNotExist(readErr):
			entry.Action = "write"
			if check {
				entry.Action = "missing"
			}
		case readErr != nil:
			entry.Action = "refuse"
			entry.Reason = readErr.Error()
		case string(existing) == content:
			entry.Action = "unchanged"
		case strings.Contains(string(existing), generatedPrefix):
			entry.Action = "update"
			if check {
				entry.Action = "stale"
			}
		case force:
			entry.Action = "update"
			entry.Reason = "overwriting a human-authored index"
		default:
			entry.Action = "refuse"
			entry.Reason = "human-authored index.md; pass --force to overwrite"
		}
		switch entry.Action {
		case "missing", "stale":
			failed = true
		case "write", "update":
			if !dryRun {
				if err := writeFileAtomic(target, content); err != nil {
					entry.Action = "failed"
					entry.Reason = err.Error()
					failed = true
				}
			}
		}
		entries = append(entries, entry)
	}

	if a.JSONL {
		items := make([]any, 0, len(entries))
		for _, entry := range entries {
			items = append(items, entry)
		}
		if err := a.writeJSONL(items); err != nil {
			return err
		}
	} else if a.JSON {
		if err := a.writeJSON("generate-index", map[string]any{
			"directories": entries,
			"dry_run":     dryRun,
			"check":       check,
		}, result.Issues); err != nil {
			return err
		}
	} else {
		for _, entry := range entries {
			line := fmt.Sprintf("%-10s %s", entry.Action, entry.Path)
			if entry.Reason != "" {
				line += "  (" + entry.Reason + ")"
			}
			fmt.Fprintln(a.Out, line)
		}
		fmt.Fprintln(a.Out, generateSummary(entries, dryRun, check))
	}
	if failed {
		return &ExitError{Code: 1}
	}
	return nil
}

// renderGeneratedIndex builds the deterministic index.md for one directory.
func renderGeneratedIndex(bundle *okf.Bundle, dir string) string {
	title := bundle.Name
	if dir != "." {
		title = path.Base(dir)
	}
	direct := directConcepts(bundle, dir)
	children := childDirs(bundle, dir)
	summary := summaryOf(descendantConcepts(bundle, dir))
	if len(children) > 0 {
		summary += fmt.Sprintf(" · %d directories", len(children))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "---\ntype: Index\ntitle: %q\ndescription: %q\ngenerated: true\n---\n\n", title, summary)
	fmt.Fprintf(&b, "%s\n\n", generatedMarker)
	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "%s\n\n", summary)
	if dir != "." {
		fmt.Fprintf(&b, "[..](../index.md)\n\n")
	}

	if len(direct) > 0 {
		b.WriteString("## Concepts\n\n")
		for _, concept := range direct {
			file := path.Base(concept.RelPath)
			parts := make([]string, 0, 4)
			if description := strings.TrimSpace(concept.Description); description != "" {
				parts = append(parts, description)
			}
			parts = append(parts, "`"+concept.Type+"`", "`"+concept.Status+"`", "`"+concept.Trust.String()+"`")
			fmt.Fprintf(&b, "- **[%s](%s)** — %s\n", concept.Title, file, strings.Join(parts, " · "))
		}
		b.WriteString("\n")
	} else if len(children) > 0 {
		b.WriteString("_No concepts directly in this directory; see the child directories._\n\n")
	}

	if len(children) > 0 {
		b.WriteString("## Directories\n\n")
		for _, child := range children {
			fmt.Fprintf(&b, "- **[%s](%s/index.md)** — %s\n", child.Name, child.Name, child.Summary)
		}
		b.WriteString("\n")
	}
	return b.String()
}

type dirEntry struct {
	Name    string
	Summary string
}

func directConcepts(bundle *okf.Bundle, dir string) []*okf.Concept {
	var out []*okf.Concept
	for _, concept := range bundle.Concepts {
		if path.Dir(concept.RelPath) == dir {
			out = append(out, concept)
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if strings.EqualFold(out[i].Title, out[j].Title) {
			return out[i].ID < out[j].ID
		}
		return strings.ToLower(out[i].Title) < strings.ToLower(out[j].Title)
	})
	return out
}

func descendantConcepts(bundle *okf.Bundle, dir string) []*okf.Concept {
	var out []*okf.Concept
	for _, concept := range bundle.Concepts {
		if dir == "." {
			out = append(out, concept)
			continue
		}
		conceptDir := path.Dir(concept.RelPath)
		if conceptDir == dir || strings.HasPrefix(conceptDir, dir+"/") {
			out = append(out, concept)
		}
	}
	return out
}

// childDirs returns the immediate subdirectories of dir that hold at least one concept, with the
// summary of everything below each one.
func childDirs(bundle *okf.Bundle, dir string) []dirEntry {
	seen := map[string]bool{}
	for _, concept := range bundle.Concepts {
		conceptDir := path.Dir(concept.RelPath)
		if conceptDir == dir {
			continue
		}
		var rest string
		switch {
		case dir == ".":
			rest = conceptDir
		case strings.HasPrefix(conceptDir, dir+"/"):
			rest = strings.TrimPrefix(conceptDir, dir+"/")
		default:
			continue
		}
		first := strings.SplitN(rest, "/", 2)[0]
		if first != "" && first != "." {
			seen[first] = true
		}
	}
	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)
	out := make([]dirEntry, 0, len(names))
	for _, name := range names {
		childDir := name
		if dir != "." {
			childDir = dir + "/" + name
		}
		out = append(out, dirEntry{Name: name, Summary: summaryOf(descendantConcepts(bundle, childDir))})
	}
	return out
}

// summaryOf renders "N concepts: Type A, Type B" with the types sorted by count and then name.
func summaryOf(concepts []*okf.Concept) string {
	if len(concepts) == 0 {
		return "0 concepts"
	}
	noun := "concepts"
	if len(concepts) == 1 {
		noun = "concept"
	}
	counts := map[string]int{}
	for _, concept := range concepts {
		conceptType := strings.TrimSpace(concept.Type)
		if conceptType == "" {
			conceptType = "unknown"
		}
		counts[conceptType]++
	}
	types := make([]string, 0, len(counts))
	for conceptType := range counts {
		types = append(types, conceptType)
	}
	sort.SliceStable(types, func(i, j int) bool {
		if counts[types[i]] != counts[types[j]] {
			return counts[types[i]] > counts[types[j]]
		}
		return types[i] < types[j]
	})
	parts := make([]string, 0, len(types))
	for _, conceptType := range types {
		parts = append(parts, fmt.Sprintf("%s %d", conceptType, counts[conceptType]))
	}
	return fmt.Sprintf("%d %s: %s", len(concepts), noun, strings.Join(parts, ", "))
}

// generateSummary is the closing line: one count per action, so a large run has a result.
func generateSummary(entries []generateEntry, dryRun, check bool) string {
	if len(entries) == 0 {
		return "no directories with concepts"
	}
	counts := map[string]int{}
	for _, entry := range entries {
		counts[entry.Action]++
	}
	var parts []string
	switch {
	case check:
		parts = []string{
			fmt.Sprintf("%d missing", counts["missing"]),
			fmt.Sprintf("%d stale", counts["stale"]),
			fmt.Sprintf("%d unchanged", counts["unchanged"]),
			fmt.Sprintf("%d foreign", counts["refuse"]),
		}
	case dryRun:
		parts = []string{
			fmt.Sprintf("%d to write", counts["write"]),
			fmt.Sprintf("%d to update", counts["update"]),
			fmt.Sprintf("%d unchanged", counts["unchanged"]),
			fmt.Sprintf("%d refused", counts["refuse"]),
		}
	default:
		parts = []string{
			fmt.Sprintf("%d written", counts["write"]),
			fmt.Sprintf("%d updated", counts["update"]),
			fmt.Sprintf("%d unchanged", counts["unchanged"]),
			fmt.Sprintf("%d refused", counts["refuse"]),
		}
	}
	if counts["failed"] > 0 {
		parts = append(parts, fmt.Sprintf("%d failed", counts["failed"]))
	}
	return fmt.Sprintf("%d directories: %s", len(entries), strings.Join(parts, ", "))
}

func writeFileAtomic(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".index-*.md")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(name, 0o644); err != nil {
		return err
	}
	return os.Rename(name, path)
}
