// Command kdn-nix-bootstrap is the stable launchd entry point on a macOS host whose Nix store
// lives on an external USB volume.
//
// macOS TCC denies access to USB volumes for any non-Apple binary running in a launchd daemon
// context, unless that exact binary path holds a Full Disk Access grant (measured 2026-10-11/12,
// docs/darwin-quirks.md). A /nix/store path changes with every nixpkgs bump, so a grant on a nix
// binary must be repeated forever. This program sits at the fixed path
// /usr/local/bin/kdn-nix-bootstrap, is granted Full Disk Access once, and runs the real daemon as
// its child: a grant on a job's top-level binary covers the whole process tree.
//
// Subcommands:
//
//	kdn-nix-bootstrap mount-store          Unlock and mount the store volume. Idempotent.
//	kdn-nix-bootstrap run <label>          Ensure the store is mounted, wait for the job's
//	                                       wait path, then spawn the job argv and mirror its exit.
//	kdn-nix-bootstrap status               Print whether the store volume is mounted.
//
// Config files are generated by system activation and never edited by hand:
//
//	/etc/kdn/nix-bootstrap/store.json        {"uuid": "...", "keychainService": "...", "mountPoint": "/nix"}
//	/etc/kdn/nix-bootstrap/jobs/<label>.json {"argv": ["/nix/store/.../nix-daemon"], "waitPath": "/nix/store", "env": {"K": "V"}}
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"os/exec"
	"os/signal"
	"path/filepath"
	"strings"
	"syscall"
	"time"
)

const (
	defaultConfigDir  = "/etc/kdn/nix-bootstrap"
	storeConfigName   = "store.json"
	jobsDirName       = "jobs"
	waitPollInterval  = 2 * time.Second
	waitTimeout       = 10 * time.Minute
	unlockedMarkerMsg = "already unlocked"
)

// StoreConfig names the external volume that holds /nix.
type StoreConfig struct {
	// UUID is the APFS volume UUID, as written in /etc/fstab.
	UUID string `json:"uuid"`
	// UnlockUUID is the volume that carries the container's System-keychain passphrase. The store
	// volume is new and its own UUID has no keychain item, but unlocking any volume of an encrypted
	// APFS container unlocks them all. Empty means unlock `UUID` itself.
	UnlockUUID string `json:"unlockUuid"`
	// KeychainService is the System-keychain generic-password item holding the volume passphrase.
	KeychainService string `json:"keychainService"`
	// MountPoint is where the volume is mounted, normally /nix.
	MountPoint string `json:"mountPoint"`
}

// JobConfig is one launchd payload: the argv to run and the path that must exist first.
type JobConfig struct {
	Argv     []string          `json:"argv"`
	WaitPath string            `json:"waitPath"`
	Env      map[string]string `json:"env"`
	// PassFds is the count of file descriptors launchd passed to this job (socket activation
	// hands the listener at descriptor 3). Go closes inherited descriptors when it spawns, so
	// the bootstrap must re-pass them through ExtraFiles or the socket-activated child loses
	// its listener.
	PassFds int `json:"passFds"`
}

// execer runs a command and returns its combined output. Tests replace it.
type execer interface {
	Run(name string, args []string, stdin io.Reader) (string, error)
}

type realExec struct{}

func (realExec) Run(name string, args []string, stdin io.Reader) (string, error) {
	cmd := exec.Command(name, args...)
	cmd.Stdin = stdin
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func main() {
	log := func(format string, args ...any) {
		fmt.Fprintf(os.Stderr, "kdn-nix-bootstrap: "+format+"\n", args...)
	}
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: kdn-nix-bootstrap mount-store | run <label> | status")
		os.Exit(2)
	}
	ex := realExec{}
	switch os.Args[1] {
	case "mount-store":
		if err := mountStore(defaultConfigDir, ex, log); err != nil {
			log("mount-store: %v", err)
			os.Exit(1)
		}
	case "status":
		state, err := storeMounted(defaultConfigDir, ex)
		if err != nil {
			log("status: %v", err)
			os.Exit(1)
		}
		fmt.Println(map[bool]string{true: "mounted", false: "absent"}[state])
	case "run":
		if len(os.Args) != 3 {
			fmt.Fprintln(os.Stderr, "usage: kdn-nix-bootstrap run <label>")
			os.Exit(2)
		}
		code, err := runJob(defaultConfigDir, os.Args[2], ex, os.Stdout, os.Stderr, log)
		if err != nil {
			log("run: %v", err)
		}
		os.Exit(code)
	default:
		fmt.Fprintln(os.Stderr, "usage: kdn-nix-bootstrap mount-store | run <label> | status")
		os.Exit(2)
	}
}

func loadStoreConfig(dir string) (StoreConfig, error) {
	var cfg StoreConfig
	raw, err := os.ReadFile(filepath.Join(dir, storeConfigName))
	if err != nil {
		return cfg, fmt.Errorf("read store config: %w", err)
	}
	if err := json.Unmarshal(raw, &cfg); err != nil {
		return cfg, fmt.Errorf("parse store config: %w", err)
	}
	if cfg.UUID == "" || cfg.MountPoint == "" || cfg.KeychainService == "" {
		return cfg, fmt.Errorf("store config needs uuid, keychainService and mountPoint, got %+v", cfg)
	}
	return cfg, nil
}

func loadJobConfig(dir, label string) (JobConfig, error) {
	var cfg JobConfig
	path := filepath.Join(dir, jobsDirName, label+".json")
	raw, err := os.ReadFile(path)
	if err != nil {
		return cfg, fmt.Errorf("read job config %s: %w", path, err)
	}
	if err := json.Unmarshal(raw, &cfg); err != nil {
		return cfg, fmt.Errorf("parse job config %s: %w", path, err)
	}
	if len(cfg.Argv) == 0 {
		return cfg, fmt.Errorf("job config %s: argv is empty", path)
	}
	if cfg.WaitPath == "" {
		cfg.WaitPath = "/nix/store"
	}
	return cfg, nil
}

// storeMounted reports whether the configured mount point holds the store volume, by looking for
// the mount line `map disk<N>s<M> on <mountPoint> (…)` in /sbin/mount output.
func storeMounted(dir string, ex execer) (bool, error) {
	cfg, err := loadStoreConfig(dir)
	if err != nil {
		return false, err
	}
	out, _ := ex.Run("/sbin/mount", nil, nil)
	for _, line := range strings.Split(out, "\n") {
		if strings.Contains(line, " on "+cfg.MountPoint+" ") || strings.Contains(line, " on "+cfg.MountPoint+" (") {
			return true, nil
		}
	}
	return false, nil
}

// mountStore brings the store volume up. It is idempotent: a mounted volume returns at once, and
// an unlocked-but-unmounted volume skips only the unlock.
func mountStore(dir string, ex execer, log func(string, ...any)) error {
	cfg, err := loadStoreConfig(dir)
	if err != nil {
		return err
	}
	mounted, err := storeMounted(dir, ex)
	if err != nil {
		return err
	}
	if mounted {
		log("store volume already mounted at %s", cfg.MountPoint)
		return nil
	}
	if err := os.MkdirAll(cfg.MountPoint, 0o755); err != nil {
		return fmt.Errorf("create mount point: %w", err)
	}
	// The unlock reads the passphrase from the System keychain and feeds it on stdin, so the
	// secret never reaches argv. `unlockVolume` also mounts; a volume already unlocked prints a
	// notice and still ends mounted.
	pw, err := ex.Run("/usr/bin/security", []string{"find-generic-password", "-s", cfg.KeychainService, "-w"}, nil)
	if err != nil {
		return fmt.Errorf("read passphrase for %s: %w", cfg.KeychainService, err)
	}
	passphrase := strings.TrimRight(pw, "\n")
	if passphrase == "" {
		return fmt.Errorf("empty passphrase for %s", cfg.KeychainService)
	}
	unlockUUID := cfg.UnlockUUID
	if unlockUUID == "" {
		unlockUUID = cfg.UUID
	}
	out, err := ex.Run("/usr/sbin/diskutil", []string{"apfs", "unlockVolume", unlockUUID, "-stdinpassphrase"}, strings.NewReader(passphrase))
	if err != nil && !strings.Contains(out, unlockedMarkerMsg) {
		return fmt.Errorf("unlock %s: %w: %s", unlockUUID, err, firstLine(out))
	}
	out, err = ex.Run("/usr/sbin/diskutil", []string{"mount", "-mountPoint", cfg.MountPoint, cfg.UUID}, nil)
	if err != nil {
		return fmt.Errorf("mount %s at %s: %w: %s", cfg.UUID, cfg.MountPoint, err, firstLine(out))
	}
	log("store volume %s mounted at %s", cfg.UUID, cfg.MountPoint)
	return nil
}

// waitPath blocks until the path exists or the timeout passes.
func waitPath(path string, timeout time.Duration) error {
	deadline := time.Now().Add(timeout)
	for {
		if _, err := os.Stat(path); err == nil {
			return nil
		}
		if time.Now().After(deadline) {
			return fmt.Errorf("timed out waiting for %s", path)
		}
		time.Sleep(waitPollInterval)
	}
}

// runJob is the launchd payload loop body: mount if needed, wait, spawn, mirror. It returns the
// exit code to report. The nix binary stays a child: exec-replacing it would move the gated
// image to the job root and TCC would deny it (measured 2026-10-12), while children of this
// granted top-level binary pass.
func runJob(dir, label string, ex execer, stdout, stderr io.Writer, log func(string, ...any)) (int, error) {
	mounted, err := storeMounted(dir, ex)
	if err != nil {
		return 1, err
	}
	if !mounted {
		if err := mountStore(dir, ex, log); err != nil {
			return 1, err
		}
	}
	job, err := loadJobConfig(dir, label)
	if err != nil {
		return 1, err
	}
	if err := waitPath(job.WaitPath, waitTimeout); err != nil {
		return 1, err
	}
	cmd := exec.Command(job.Argv[0], job.Argv[1:]...)
	cmd.Stdout = stdout
	cmd.Stderr = stderr
	cmd.Env = os.Environ()
	for k, v := range job.Env {
		cmd.Env = append(cmd.Env, k+"="+v)
	}
	if job.PassFds > 0 {
		fds, err := launchdFds(job.PassFds)
		if err != nil {
			return 1, err
		}
		cmd.ExtraFiles = fds
	}
	if err := cmd.Start(); err != nil {
		return 1, fmt.Errorf("spawn %s: %w", job.Argv[0], err)
	}
	log("%s spawned pid %d", label, cmd.Process.Pid)
	// Forward the termination signals launchd sends, so the child exits cleanly and the
	// KeepAlive policy sees the real status.
	sigs := make(chan os.Signal, 1)
	signal.Notify(sigs, syscall.SIGTERM, syscall.SIGHUP, syscall.SIGINT)
	done := make(chan error, 1)
	go func() { done <- cmd.Wait() }()
	select {
	case err := <-done:
		if err == nil {
			return 0, nil
		}
		var ee *exec.ExitError
		if ok := asExitError(err, &ee); ok {
			return clampCode(ee.ExitCode()), nil
		}
		return 1, err
	case s := <-sigs:
		_ = cmd.Process.Signal(s)
		err := <-done
		_ = cmd.Process.Signal(syscall.SIGKILL)
		if err == nil {
			return 0, nil
		}
		var ee *exec.ExitError
		if ok := asExitError(err, &ee); ok {
			return clampCode(ee.ExitCode()), nil
		}
		return 1, err
	}
}

// launchdFds collects the first `count` descriptors launchd placed for socket activation.
// launchd starts handing sockets at descriptor 3, and Go closes inherited descriptors when it
// spawns, so each one must be re-passed through ExtraFiles. A descriptor that is not open is an
// error: a socket-activated job that silently loses its listener just wedges.
func launchdFds(count int) ([]*os.File, error) {
	files := make([]*os.File, 0, count)
	for i := 0; i < count; i++ {
		fd := uintptr(3 + i)
		if _, _, errno := syscall.Syscall(syscall.SYS_FCNTL, fd, syscall.F_GETFD, 0); errno != 0 {
			return nil, fmt.Errorf("descriptor %d is not open: %w", fd, errno)
		}
		files = append(files, os.NewFile(fd, fmt.Sprintf("launchd-%d", fd)))
	}
	return files, nil
}

// clampCode turns a signal death (-1) into a plain failure code.
func clampCode(code int) int {
	if code < 0 {
		return 1
	}
	return code
}

func asExitError(err error, target **exec.ExitError) bool {
	ee, ok := err.(*exec.ExitError)
	if ok {
		*target = ee
	}
	return ok
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i]
	}
	return strings.TrimSpace(s)
}
